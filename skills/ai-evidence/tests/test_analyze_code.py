# --- CLI and scoring integration ----------------------------------------------------------------------

def run(*args):
    return subprocess.run([sys.executable, str(SCRIPTS / "analyze_code.py"), *map(str, args)], capture_output=True, text=True, timeout=120)


def test_cli_refuses_to_overwrite_missing_paths_and_bad_extensions(tmp_path):
    root = repo(tmp_path, {"a.py": "x = 1\n"})
    out = tmp_path / "e.json"
    assert run(root, "--out", out).returncode == 0 and run(root, "--out", out).returncode != 0
    assert run(root, "--out", out, "--force").returncode == 0 and run(root, "--out", tmp_path / "x.txt").returncode != 0
    assert run(tmp_path / "nope").returncode != 0 and run(root, "--git-log", tmp_path / "nope.txt").returncode != 0


def test_code_report_uses_code_wording_the_notice_and_the_style_cap(tmp_path):
    root = repo(tmp_path, {"a.py": narrating_module() + "\n".join(f"# Step {i}: x" for i in range(1, 6)) + "\nprint('✅ ok')\n" * 6, "CLAUDE.md": "rules"})
    evidence = tmp_path / "e.json"
    assert run(root, "--out", evidence).returncode == 0
    report = tmp_path / "r.html"
    done = subprocess.run([sys.executable, str(SCRIPTS / "score_evidence.py"), str(evidence), "--out", str(report), "--lang", "en"], capture_output=True, text=True)
    assert done.returncode == 0, done.stderr
    html = report.read_text(encoding="utf-8")
    assert "Largely written by AI?" in html and "Built with AI assistance?" in html and "Code measurements" in html
    assert "Using AI to write code is normal and legitimate" in html and "does not accuse anyone" in html and "<script" not in html
    summary = json.loads(done.stdout)
    assert summary["assessment"]["ai_edited"]["score"] >= 8                       # the config file decides the "assisted" question
    assert summary["assessment"]["generated"]["confidence"] in ("low", "very_low")   # style alone stays weak
    es = subprocess.run([sys.executable, str(SCRIPTS / "score_evidence.py"), str(evidence), "--out", str(tmp_path / "r_es.html")], capture_output=True, text=True)
    assert "¿Hecho con ayuda de IA?" in (tmp_path / "r_es.html").read_text(encoding="utf-8") and es.returncode == 0


