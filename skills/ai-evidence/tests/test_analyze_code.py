# --- git log ----------------------------------------------------------------------------------------

def log_record(sha, date, subject, body="", added=10):
    return f"\x1e{sha}\x1f{date}\x1f{subject}\x1f{body}\x1d\n\n{added}\t0\tfile.py\n"


def test_commit_trailers_are_reported_by_tool_name_and_never_by_person(tmp_path):
    root = repo(tmp_path, {"a.py": "x = 1\n"})
    records = [log_record(f"{i:040x}", f"2025-01-0{i % 9 + 1}T10:00:00+00:00", f"feat: thing {i}",
                          "Body.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nCo-Authored-By: Claude <noreply@anthropic.com>" if i < 6 else "Body.") for i in range(8)]
    result = ac.analyze(root, "".join(records))
    found = ids(result)
    item = found["cd-commit-trailers"]
    assert item["claim"] == "ai_edited" and item["weight"] == 0.9 and "6 of 8" in item["title"]["en"] and "claude" in item["title"]["en"].lower()
    assert found["cd-commit-trailers-share"]["claim"] == "generated"
    assert "noreply" not in json.dumps(result) and "anthropic.com" not in json.dumps(result)


def test_history_shape_bursts_and_messy_history(tmp_path):
    root = repo(tmp_path, {"a.py": "x = 1\n"})
    dump = ac.analyze(root, log_record("a" * 40, "2025-01-01T10:00:00+00:00", "initial commit", added=3000) + log_record("b" * 40, "2025-01-02T10:00:00+00:00", "tweak", added=20))
    assert "cd-history-shape" in ids(dump)
    burst = "".join(log_record(f"{i:040x}", f"2025-01-01T10:{i // 30:02d}:{(i * 2) % 60:02d}+00:00", f"change {i}", added=5) for i in range(30))
    assert "cd-history-bursts" in ids(ac.analyze(root, burst))
    messy = "".join(log_record(f"{i:040x}", f"2025-01-{i % 28 + 1:02d}T10:00:00+00:00", ["wip", "fix typo", "update", "add parser"][i % 4], added=5) for i in range(20))
    assert ids(ac.analyze(root, messy))["cd-messy-history"]["score"] < 5


