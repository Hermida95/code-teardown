def repo(tmp_path, files: dict, name="proj") -> Path:
    root = tmp_path / name
    for rel, content in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return root


def ids(result: dict) -> dict:
    return {e["id"]: e for e in result["evidence"]}


def narrating_module(n=60):
    out = ["import os", ""]
    for i in range(n):
        out += [f"def func_{i}(value_{i}):", f"    # Initialize the result list", "    result = []", f"    # Loop through the value_{i} items", f"    for item in value_{i}:", "        # Append the item to the result", "        result.append(item)", "    return result", ""]
    return "\n".join(out)


def human_module(n=70):
    out = ["import os", ""]
    for i in range(n):
        out += [f"def f{i}(x):", "    r = []", "    for y in x:", "        if y % 3:", "            r.append(y * 2)", "    return r", ""]
    return "\n".join(out)


def documented_module(n=14):
    out = []
    for i in range(n):
        out += [f"def helper_{i}(a, b):", '    """Add two values.', "", "    Args:", "        a: first", "        b: second", "", "    Returns:", "        The sum.", '    """', "    return a + b", ""]
    return "\n".join(out * 1) + "\n" + human_module(40)


