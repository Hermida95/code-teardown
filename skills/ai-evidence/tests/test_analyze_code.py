def test_assistant_configuration_files_point_to_assistance_not_authorship(tmp_path):
    root = repo(tmp_path, {"CLAUDE.md": "rules", ".cursor/rules/a.mdc": "x", "src/app.py": "print(1)\n"})
    item = ids(ac.analyze(root))["cd-ai-tool-files"]
    assert item["claim"] == "ai_edited" and item["weight"] == 0.8 < se.CONCLUSIVE and "CLAUDE.md" in item["where"]
    assert "cd-ai-tool-files" not in ids(ac.analyze(repo(tmp_path, {"src/app.py": "print(1)\n"}, "clean")))


def test_a_symlinked_assistant_file_is_not_followed_or_counted(tmp_path):
    root = repo(tmp_path, {"src/app.py": "print(1)\n"})
    (root / "CLAUDE.md").symlink_to(tmp_path / "somewhere")
    assert "cd-ai-tool-files" not in ids(ac.analyze(root))


def test_placeholders_in_real_comments_count_but_the_same_text_in_strings_does_not(tmp_path):
    hit = repo(tmp_path, {"a.py": "def f():\n    pass\n\n# ... rest of the code remains the same\n"}, "hit")
    assert ids(ac.analyze(hit))["cd-llm-placeholders"]["weight"] == 0.6
    js = repo(tmp_path, {"a.js": "function f() {}\n// rest of the file remains unchanged\n"}, "js")
    assert "cd-llm-placeholders" in ids(ac.analyze(js))
    # a detector, a linter or a test fixture that merely *contains* the phrase must not be flagged
    safe = repo(tmp_path, {"d.py": 'PATTERN = re.compile(r"# rest of the code remains the same")\nTEXT = "// your code here"\nDOC = """... rest of the code ..."""\n'}, "safe")
    assert "cd-llm-placeholders" not in ids(ac.analyze(safe))


